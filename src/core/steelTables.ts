export function findProfile(family: string, name: string): { family: SteelFamily; profile: SteelProfile } | null {
  const f = STEEL_FAMILIES.find((x) => x.key === family);
  const p = f?.profiles.find((x) => x.name === name);
  return f && p ? { family: f, profile: p } : null;
}

