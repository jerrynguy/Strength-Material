/**
 * Bảng thép hình tiêu chuẩn.
 *
 * Mỗi thép hình được mô tả bằng kích thước danh nghĩa (mm) để dựng đúng hình học mặt cắt
 * (có góc lượn chân, vát mép, cánh dốc với thép GOST). Mọi đặc trưng (A, I, W, S, ứng suất...)
 * được tính lại từ hình học đó; giá trị tra bảng (ref) chỉ dùng để đối chiếu và kiểm thử.
 *
 * Nguồn kích thước:
 *  - IPE, HEA, HEB: EN 10365 (châu Âu)
 *  - H: JIS G3192 (Nhật — phổ biến ở Việt Nam)
 *  - I, U: GOST 8239-89, GOST 8240-89 (bảng tra thường dùng trong giáo trình SBVL ở Việt Nam)
 *  - L đều cạnh: GOST 8509-93
 *  - Ống tròn, hộp vuông/chữ nhật: kích thước thương mại phổ biến, góc lượn hộp theo EN 10219
 * Hãy đối chiếu với catalogue của nhà sản xuất trước khi dùng cho hồ sơ thiết kế.
 */

export type ProfileGeom =
  /** Chữ I/H: cao h, rộng b, bụng tw, cánh tf, bán kính chân r; slope: độ dốc mặt trong cánh; r2: lượn mép cánh */
  | { type: 'I'; h: number; b: number; tw: number; tf: number; r: number; slope?: number; r2?: number }
  /** Chữ U (máng) */
  | { type: 'U'; h: number; b: number; tw: number; tf: number; r: number; slope?: number; r2?: number }
  /** Thép góc đều cạnh */
  | { type: 'L'; b: number; t: number; r: number; r2: number }
  /** Ống tròn */
  | { type: 'CHS'; D: number; t: number }
  /** Hộp chữ nhật / vuông (H cao, B rộng) */
  | { type: 'RHS'; H: number; B: number; t: number };

export interface SteelProfile {
  name: string;
  geom: ProfileGeom;
  /** Giá trị tra bảng để đối chiếu: A (cm²), Ix (cm⁴) */
  ref?: { A: number; Ix: number };
}

export interface SteelFamily {
  key: string;
  label: string;
  standard: string;
  profiles: SteelProfile[];
}

const I = (name: string, h: number, b: number, tw: number, tf: number, r: number, A: number, Ix: number, slope?: number, r2?: number): SteelProfile => ({
  name, geom: { type: 'I', h, b, tw, tf, r, slope, r2 }, ref: { A, Ix },
});
const U = (name: string, h: number, b: number, tw: number, tf: number, r: number, r2: number, A: number, Ix: number): SteelProfile => ({
  name, geom: { type: 'U', h, b, tw, tf, r, slope: 0.1, r2 }, ref: { A, Ix },
});
const L = (b: number, t: number, R: number, A: number, Ix: number): SteelProfile => ({
  name: `L${b}×${t}`, geom: { type: 'L', b, t, r: R, r2: R / 3 }, ref: { A, Ix },
});

